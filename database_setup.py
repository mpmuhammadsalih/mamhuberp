"""First-run wizard: choose Single vs Multi-Oracle-DB, save ``.env``, test connection, bootstrap tables."""
from __future__ import annotations
import importlib
import os
import secrets
from pathlib import Path
from urllib.parse import quote
from db.oracle_driver import oracle_connect
from dotenv import set_key as dotenv_set_key
from nexa_http import Blueprint, abort, current_app, flash, redirect, render_template, request, session, url_for
ROOT = Path(__file__).resolve().parent
bp = Blueprint('database_setup', __name__, url_prefix='/database-setup', template_folder=str(ROOT / 'templates'))

def _env_path() -> Path:
    return ROOT / '.env'

def database_setup_page_allowed() -> bool:
    """False if disabled; True if first run / not configured / override env."""
    if (os.getenv('DATABASE_SETUP_DISABLED') or '').strip().lower() in ('1', 'true', 'yes', 'on'):
        return False
    if (os.getenv('DATABASE_SETUP_ALWAYS') or '').strip().lower() in ('1', 'true', 'yes', 'on'):
        return True
    if (os.getenv('ALLOW_DATABASE_SETUP_WHILE_CONFIGURED') or '').strip().lower() in ('1', 'true', 'yes', 'on'):
        return True
    from config import settings as s
    dc = (s.DB_DSN or '').strip() and (s.DB_USERNAME or '').strip()
    ac = (s.AUTH_DB_DSN or '').strip() and (s.AUTH_DB_USERNAME or '').strip()
    return not (dc or ac)

def _db_credentials_present() -> bool:
    from config import settings as s
    dc = (s.DB_DSN or '').strip() and (s.DB_USERNAME or '').strip()
    ac = (s.AUTH_DB_DSN or '').strip() and (s.AUTH_DB_USERNAME or '').strip()
    return bool(dc or ac)

def _session_user_is_privileged(username: str | None) -> bool:
    return (username or '').strip().lower() in ('admin', 'super')

def _privileged_login_for_setup(session_user: str | None) -> bool:
    """Privileged user (``admin`` / ``super``) may open the editor when not blocked by env."""
    if (os.getenv('DATABASE_SETUP_NO_ADMIN_EDIT') or '').strip().lower() in ('1', 'true', 'yes', 'on'):
        return False
    return _session_user_is_privileged(session_user)

def _admin_may_edit_configured_db() -> bool:
    """When True, signed-in privileged user can open the wizard without ALLOW_* env."""
    return _privileged_login_for_setup(session.get('user')) and _db_credentials_present()

def database_setup_can_access_wizard() -> bool:
    """Whether GET/POST /database-setup should show the full wizard (not the locked status page)."""
    if (os.getenv('DATABASE_SETUP_DISABLED') or '').strip().lower() in ('1', 'true', 'yes', 'on'):
        return False
    if database_setup_page_allowed():
        return True
    if session.get('database_setup_unlock_ok'):
        return True
    if _admin_may_edit_configured_db():
        return True
    return False

def _patch_db_after_settings_reload() -> None:
    """Point ``db`` module callables at freshly reloaded ``config.settings``."""
    import db as db_module
    import config.settings as settings_module
    db_module.get_db_config = settings_module.get_db_config
    db_module.get_auth_db_config = settings_module.get_auth_db_config
    db_module.get_central_report_config = settings_module.get_central_report_config
    db_module.is_multi_db_mode = settings_module.is_multi_db_mode

def _reload_settings_from_disk() -> None:
    from config.bootstrap_env import bootstrap_dotenv
    bootstrap_dotenv()
    import config.settings as settings_module
    importlib.reload(settings_module)
    _patch_db_after_settings_reload()

def _set_env_line(key: str, value: str) -> None:
    p = _env_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    if not p.is_file():
        p.write_text('# RGC Dynamics — generated by database setup wizard\n', encoding='utf-8')
    dotenv_set_key(str(p), key, value or '')

def _test_oracle(user: str, password: str, dsn: str) -> None:
    conn = oracle_connect(user=(user or '').strip(), password=password or '', dsn=(dsn or '').strip())
    conn.close()

def _oracle_credentials_configured(inst) -> bool:
    """True when current settings already have a usable Oracle connection (single or auth)."""
    dc = (getattr(inst, 'DB_DSN', '') or '').strip() and (getattr(inst, 'DB_USERNAME', '') or '').strip()
    ac = (getattr(inst, 'AUTH_DB_DSN', '') or '').strip() and (getattr(inst, 'AUTH_DB_USERNAME', '') or '').strip()
    return bool(dc or ac)

def _status_page_context():
    """Context for locked / informational view when the wizard cannot be opened yet."""
    import config.settings as s
    mode = 'multi' if s.is_multi_db_mode() else 'single'
    has_unlock_key = bool((os.getenv('DATABASE_SETUP_EDIT_KEY') or '').strip())
    session['database_setup_unlock_token'] = secrets.token_hex(16)
    wiz = url_for('database_setup.wizard')
    login = url_for('auth.login')
    try:
        dash = url_for('dashboard.dashboard')
    except Exception:
        dash = login
    cu = session.get('user')
    no_admin_edit = (os.getenv('DATABASE_SETUP_NO_ADMIN_EDIT') or '').strip().lower() in ('1', 'true', 'yes', 'on')
    return {'status_mode': mode, 'status_single_user': (s.DB_USERNAME or '').strip(), 'status_single_dsn': (s.DB_DSN or '').strip(), 'status_auth_user': (s.AUTH_DB_USERNAME or '').strip(), 'status_auth_dsn': (s.AUTH_DB_DSN or '').strip(), 'login_url': login, 'login_url_with_next': f"{login}?next={quote(wiz, safe='')}", 'wizard_url': wiz, 'dashboard_url': dash, 'dashboard_after_login': f"{login}?next={quote(dash, safe='')}", 'has_edit_unlock_key': has_unlock_key, 'unlock_token': session['database_setup_unlock_token'], 'current_user': cu, 'current_user_is_privileged': _session_user_is_privileged(cu), 'admin_edit_available': not no_admin_edit, 'wizard_disabled': (os.getenv('DATABASE_SETUP_DISABLED') or '').strip().lower() in ('1', 'true', 'yes', 'on')}

@bp.route('/unlock', methods=('POST',))
def unlock():
    """Optional shared secret from .env lets non-admin users open the wizard for one browser session."""
    if (os.getenv('DATABASE_SETUP_DISABLED') or '').strip().lower() in ('1', 'true', 'yes', 'on'):
        flash('Database setup is disabled in server configuration.', 'error')
        return redirect(url_for('database_setup.wizard'))
    tok = session.get('database_setup_unlock_token') or ''
    if not tok or (request.form.get('unlock_token') or '') != tok:
        flash('Unlock session expired — open the Database setup page again.', 'error')
        return redirect(url_for('database_setup.wizard'))
    expected = (os.getenv('DATABASE_SETUP_EDIT_KEY') or '').strip()
    if not expected:
        flash('DATABASE_SETUP_EDIT_KEY is not configured on the server.', 'error')
        return redirect(url_for('database_setup.wizard'))
    given = (request.form.get('edit_key') or '').strip()
    if not secrets.compare_digest(given, expected):
        flash('Incorrect setup key.', 'error')
        return redirect(url_for('database_setup.wizard'))
    session['database_setup_unlock_ok'] = True
    session.pop('database_setup_unlock_token', None)
    flash('You can edit database configuration for this browser session.', 'success')
    return redirect(url_for('database_setup.wizard'))

@bp.route('', methods=('GET', 'POST'))
@bp.route('/', methods=('GET', 'POST'))
def wizard():
    if not database_setup_can_access_wizard():
        if request.method == 'POST':
            return redirect(url_for('database_setup.wizard'))
        return render_template('database_setup_status.html', **_status_page_context())
    if request.method == 'GET':
        session['database_setup_token'] = secrets.token_hex(24)
        import config.settings as s
        mode = 'multi' if s.is_multi_db_mode() else 'single'
        editing_existing = not database_setup_page_allowed()
        show_initial_app_login = not _oracle_credentials_configured(s)
        try:
            from db import list_app_owned_bootstrap_step_names
            bootstrap_extended_steps = list_app_owned_bootstrap_step_names()
        except Exception:
            bootstrap_extended_steps = []
        return render_template('database_setup.html', mode=mode, single_user=s.DB_USERNAME, single_pass='', single_dsn=s.DB_DSN, auth_user=s.AUTH_DB_USERNAME, auth_pass='', auth_dsn=s.AUTH_DB_DSN, auto_full=os.getenv('AUTO_ENSURE_FULL_SCHEMA', '').strip().lower() in ('1', 'true', 'yes', 'on'), bootstrap_multi=os.getenv('BOOTSTRAP_SCHEMA_ALL_ACTIVE_TENANTS', '').strip().lower() in ('1', 'true', 'yes', 'on'), flask_secret_ok=bool((os.getenv('FLASK_SECRET_KEY') or '').strip()) and os.getenv('FLASK_SECRET_KEY', '') != 'change-me', setup_token=session['database_setup_token'], editing_existing=editing_existing, show_initial_app_login=show_initial_app_login, bootstrap_extended_steps=bootstrap_extended_steps)
    tok = session.get('database_setup_token') or ''
    if not tok or (request.form.get('setup_token') or '') != tok:
        flash('Setup session expired — open the Database setup page again.', 'error')
        return redirect(url_for('database_setup.wizard'))
    import config.settings as s_before
    allow_initial_app_login = not _oracle_credentials_configured(s_before)
    initial_login_username: str | None = None
    initial_login_password: str | None = None
    if allow_initial_app_login:
        iau = (request.form.get('app_login_username') or '').strip()
        iap = request.form.get('app_login_password') or ''
        iap2 = request.form.get('app_login_password_confirm') or ''
        if iau:
            if len(iau) > 100:
                flash('Application username is too long (max 100 characters).', 'error')
                return redirect(url_for('database_setup.wizard'))
            if not iap.strip():
                flash('Enter a password for the application login user, or clear the username to use defaults (admin / admin123).', 'error')
                return redirect(url_for('database_setup.wizard'))
            if iap != iap2:
                flash('Application login passwords do not match.', 'error')
                return redirect(url_for('database_setup.wizard'))
            if len(iap) < 4:
                flash('Application login password must be at least 4 characters.', 'error')
                return redirect(url_for('database_setup.wizard'))
            initial_login_username = iau
            initial_login_password = iap
    mode = (request.form.get('db_mode') or 'single').strip().lower()
    if mode not in ('single', 'multi'):
        mode = 'single'
    flask_secret = (request.form.get('flask_secret_key') or '').strip()
    updates: dict[str, str] = {}
    if mode == 'single':
        u = (request.form.get('db_username') or '').strip()
        p = request.form.get('db_password') or ''
        d = (request.form.get('db_dsn') or '').strip()
        if not u or not d:
            flash('Single-DB mode: Oracle user and DSN are required.', 'error')
            return redirect(url_for('database_setup.wizard'))
        updates['DB_USERNAME'] = u
        updates['DB_PASSWORD'] = p
        updates['DB_DSN'] = d
        updates['AUTH_DB_USERNAME'] = ''
        updates['AUTH_DB_PASSWORD'] = ''
        updates['AUTH_DB_DSN'] = ''
    else:
        u = (request.form.get('auth_username') or '').strip()
        p = request.form.get('auth_password') or ''
        d = (request.form.get('auth_dsn') or '').strip()
        if not u or not d:
            flash('Multi-DB mode: Auth Oracle user and DSN are required.', 'error')
            return redirect(url_for('database_setup.wizard'))
        updates['AUTH_DB_USERNAME'] = u
        updates['AUTH_DB_PASSWORD'] = p
        updates['AUTH_DB_DSN'] = d
        if (request.form.get('mirror_db_to_same') or '').strip() == 'on':
            updates['DB_USERNAME'] = u
            updates['DB_PASSWORD'] = p
            updates['DB_DSN'] = d
        else:
            updates['DB_USERNAME'] = ''
            updates['DB_PASSWORD'] = ''
            updates['DB_DSN'] = ''
    if flask_secret:
        updates['FLASK_SECRET_KEY'] = flask_secret
    elif not (os.getenv('FLASK_SECRET_KEY') or '').strip() or os.getenv('FLASK_SECRET_KEY', '') == 'change-me':
        updates['FLASK_SECRET_KEY'] = secrets.token_urlsafe(48)
    if (request.form.get('auto_full_schema') or '').strip() == 'on':
        updates['AUTO_ENSURE_FULL_SCHEMA'] = '1'
    else:
        updates['AUTO_ENSURE_FULL_SCHEMA'] = '0'
    if mode == 'multi' and (request.form.get('bootstrap_all_tenants') or '').strip() == 'on':
        updates['BOOTSTRAP_SCHEMA_ALL_ACTIVE_TENANTS'] = '1'
    else:
        updates['BOOTSTRAP_SCHEMA_ALL_ACTIVE_TENANTS'] = '0'
    try:
        if mode == 'single':
            _test_oracle(updates['DB_USERNAME'], updates['DB_PASSWORD'], updates['DB_DSN'])
        else:
            _test_oracle(updates['AUTH_DB_USERNAME'], updates['AUTH_DB_PASSWORD'], updates['AUTH_DB_DSN'])
    except Exception as ex:
        flash(f'Oracle connection test failed: {ex}', 'error')
        return redirect(url_for('database_setup.wizard'))
    for k, v in updates.items():
        _set_env_line(k, v)
    os.environ.update(updates)
    _reload_settings_from_disk()
    try:
        from db import bootstrap_application_schema
        bootstrap_application_schema(current_app, initial_login_username=initial_login_username, initial_login_password=initial_login_password)
    except Exception as ex:
        current_app.logger.exception('bootstrap_application_schema after setup')
        flash(f'.env saved and connection verified, but table bootstrap logged an error (you can restart the app): {ex}', 'warning')
    else:
        suffix = ''
        if allow_initial_app_login and initial_login_username:
            suffix = f' Application login: use username "{initial_login_username}" with the password you set here.'
        elif allow_initial_app_login:
            suffix = ' Application login: default user admin — password admin123 (change after first login).'
        flash('Configuration saved. Core tables managed by db.ensure_* / bootstrap were applied. Oracle views/triggers remain your DBA scripts unless added to code.' + suffix, 'success')
    session['database_setup_finished'] = True
    session.pop('database_setup_token', None)
    return redirect(url_for('database_setup.done'))

@bp.route('/complete', endpoint='done')
def done():
    """Success page (only after wizard POST)."""
    if not session.pop('database_setup_finished', None):
        abort(404)
    return render_template('database_setup_done.html', login_url=url_for('auth.login'), setup_url=url_for('database_setup.wizard'), setup_allowed=database_setup_can_access_wizard())

def is_database_setup_route() -> bool:
    """True when request targets this blueprint — use to bypass auth/location/menu hooks."""
    from nexa_http import has_request_context
    from nexa_http.request_wrap import request
    if not has_request_context():
        return False
    ep = getattr(request, 'endpoint', None) or ''
    if ep.startswith('database_setup.'):
        return True
    return (request.path or '').startswith('/database-setup')
