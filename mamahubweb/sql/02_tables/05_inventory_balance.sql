-- =============================================================================
-- INVENTORY_BALANCE
-- Stock by product / warehouse / batch
-- =============================================================================

CREATE TABLE INVENTORY_BALANCE (
    INVENTORY_BALANCE_ID    NUMBER          NOT NULL,
    PRODUCT_ID              NUMBER          NOT NULL,
    PRODUCT_VARIANT_ID      NUMBER,
    WAREHOUSE_ID            NUMBER          NOT NULL,
    STORE_ID                NUMBER,
    BATCH_NO                VARCHAR2(50)    DEFAULT 'DEFAULT' NOT NULL,
    QTY_ON_HAND             NUMBER(14,3)    DEFAULT 0 NOT NULL,
    QTY_RESERVED            NUMBER(14,3)    DEFAULT 0 NOT NULL,
    QTY_AVAILABLE           NUMBER(14,3)    DEFAULT 0 NOT NULL,
    QTY_DAMAGED             NUMBER(14,3)    DEFAULT 0 NOT NULL,
    QTY_IN_TRANSIT          NUMBER(14,3)    DEFAULT 0 NOT NULL,
    SAFETY_STOCK            NUMBER(14,3)    DEFAULT 0 NOT NULL,
    REORDER_LEVEL           NUMBER(14,3)    DEFAULT 0 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_INVENTORY_BALANCE PRIMARY KEY (INVENTORY_BALANCE_ID),
    CONSTRAINT UQ_INVENTORY_BALANCE UNIQUE (PRODUCT_ID, WAREHOUSE_ID, BATCH_NO),
    CONSTRAINT CK_INV_QTY_ON_HAND CHECK (QTY_ON_HAND >= 0),
    CONSTRAINT CK_INV_QTY_RESERVED CHECK (QTY_RESERVED >= 0),
    CONSTRAINT CK_INV_QTY_AVAILABLE CHECK (QTY_AVAILABLE >= 0),
    CONSTRAINT CK_INV_QTY_DAMAGED CHECK (QTY_DAMAGED >= 0),
    CONSTRAINT CK_INV_QTY_TRANSIT CHECK (QTY_IN_TRANSIT >= 0)
);
