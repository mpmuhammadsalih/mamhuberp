-- Auth support tables (create-if-missing, MH_ prefix)
CREATE TABLE MH_REFRESH_TOKEN (
    REFRESH_TOKEN_ID        NUMBER          NOT NULL,
    USER_ID                 NUMBER          NOT NULL,
    TOKEN_JTI               VARCHAR2(64)    NOT NULL,
    EXPIRES_AT              TIMESTAMP       NOT NULL,
    REVOKED                 NUMBER(1)       DEFAULT 0 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    REVOKED_AT              TIMESTAMP,
    CONSTRAINT PK_MH_REFRESH_TOKEN PRIMARY KEY (REFRESH_TOKEN_ID),
    CONSTRAINT UQ_MH_REFRESH_JTI UNIQUE (TOKEN_JTI),
    CONSTRAINT CK_MH_REFRESH_REVOKED CHECK (REVOKED IN (0, 1))
);

CREATE TABLE MH_LOGIN_HISTORY (
    LOGIN_HISTORY_ID        NUMBER          NOT NULL,
    USER_ID                 NUMBER,
    USERNAME                VARCHAR2(100),
    SUCCESS                 NUMBER(1)       NOT NULL,
    FAILURE_REASON          VARCHAR2(255),
    IP_ADDRESS              VARCHAR2(45),
    USER_AGENT              VARCHAR2(500),
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MH_LOGIN_HISTORY PRIMARY KEY (LOGIN_HISTORY_ID),
    CONSTRAINT CK_MH_LOGIN_SUCCESS CHECK (SUCCESS IN (0, 1))
);
