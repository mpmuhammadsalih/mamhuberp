    INTEREST_ID             NUMBER          NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    CONSTRAINT PK_MH_ITEM_INTEREST PRIMARY KEY (ITEM_INTEREST_ID),
    CONSTRAINT UQ_MH_ITEM_INTEREST UNIQUE (LOCATION_CODE, ITEM_CODE, INTEREST_ID)
