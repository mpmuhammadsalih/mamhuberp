-- =============================================================================
-- MamaHub ecommerce extension tables (create only if missing)
-- Uses MH_ prefix to avoid colliding with existing ERP objects.
-- NEVER drop/replace ERP tables such as CATEGORY, ITEMMASTER, CUSTOMER.
-- =============================================================================

CREATE TABLE MH_AGE_GROUP (
    AGE_GROUP_ID            NUMBER          NOT NULL,
    AGE_GROUP_CODE          VARCHAR2(50)    NOT NULL,
    AGE_GROUP_NAME          VARCHAR2(100)   NOT NULL,
    SLUG                    VARCHAR2(120)   NOT NULL,
    MIN_AGE_MONTHS          NUMBER          DEFAULT 0 NOT NULL,
    MAX_AGE_MONTHS          NUMBER,
    DESCRIPTION             VARCHAR2(500),
    SORT_ORDER              NUMBER          DEFAULT 0 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_MH_AGE_GROUP PRIMARY KEY (AGE_GROUP_ID),
    CONSTRAINT UQ_MH_AGE_GROUP_CODE UNIQUE (AGE_GROUP_CODE),
    CONSTRAINT UQ_MH_AGE_GROUP_SLUG UNIQUE (SLUG),
    CONSTRAINT CK_MH_AGE_GROUP_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE MH_BRAND (
    BRAND_ID                NUMBER          NOT NULL,
    BRAND_CODE              VARCHAR2(50)    NOT NULL,
    BRAND_NAME              VARCHAR2(200)   NOT NULL,
    SLUG                    VARCHAR2(220)   NOT NULL,
    DESCRIPTION             VARCHAR2(1000),
    LOGO_URL                VARCHAR2(500),
    WEBSITE_URL             VARCHAR2(500),
    ERP_BRAND_CODE          NUMBER,
    SORT_ORDER              NUMBER          DEFAULT 0 NOT NULL,
    IS_FEATURED             NUMBER(1)       DEFAULT 0 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_MH_BRAND PRIMARY KEY (BRAND_ID),
    CONSTRAINT UQ_MH_BRAND_CODE UNIQUE (BRAND_CODE),
    CONSTRAINT UQ_MH_BRAND_SLUG UNIQUE (SLUG),
    CONSTRAINT CK_MH_BRAND_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE MH_INTEREST (
    INTEREST_ID             NUMBER          NOT NULL,
    INTEREST_CODE           VARCHAR2(50)    NOT NULL,
    INTEREST_NAME           VARCHAR2(100)   NOT NULL,
    SLUG                    VARCHAR2(120)   NOT NULL,
    DESCRIPTION             VARCHAR2(500),
    SORT_ORDER              NUMBER          DEFAULT 0 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_MH_INTEREST PRIMARY KEY (INTEREST_ID),
    CONSTRAINT UQ_MH_INTEREST_CODE UNIQUE (INTEREST_CODE),
    CONSTRAINT UQ_MH_INTEREST_SLUG UNIQUE (SLUG),
    CONSTRAINT CK_MH_INTEREST_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE MH_ITEM_AGE_GROUP (
    ITEM_AGE_GROUP_ID       NUMBER          NOT NULL,
    LOCATION_CODE           NUMBER          NOT NULL,
    ITEM_CODE               NUMBER          NOT NULL,
    AGE_GROUP_ID            NUMBER          NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    CONSTRAINT PK_MH_ITEM_AGE_GROUP PRIMARY KEY (ITEM_AGE_GROUP_ID),
    CONSTRAINT UQ_MH_ITEM_AGE_GROUP UNIQUE (LOCATION_CODE, ITEM_CODE, AGE_GROUP_ID)
);

CREATE TABLE MH_ITEM_INTEREST (
    ITEM_INTEREST_ID        NUMBER          NOT NULL,
