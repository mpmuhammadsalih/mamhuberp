-- Delivery zones/slots and pickup stores.

CREATE TABLE MH_DELIVERY_ZONE (
    DELIVERY_ZONE_ID        NUMBER          NOT NULL,
    ZONE_CODE               VARCHAR2(50)    NOT NULL,
    ZONE_NAME               VARCHAR2(150)   NOT NULL,
    CITY                    VARCHAR2(100)   NOT NULL,
    DELIVERY_FEE            NUMBER(18,4)    DEFAULT 0 NOT NULL,
    MIN_ORDER_AMOUNT        NUMBER(18,4)    DEFAULT 0 NOT NULL,
    FREE_DELIVERY_THRESHOLD NUMBER(18,4),
    ESTIMATED_DAYS          NUMBER          DEFAULT 2 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MH_DELIVERY_ZONE PRIMARY KEY (DELIVERY_ZONE_ID),
    CONSTRAINT UQ_MH_DELIVERY_ZONE_CODE UNIQUE (ZONE_CODE),
    CONSTRAINT CK_MH_DELIVERY_ZONE_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE MH_DELIVERY_SLOT (
    DELIVERY_SLOT_ID        NUMBER          NOT NULL,
    SLOT_CODE               VARCHAR2(50)    NOT NULL,
    SLOT_LABEL              VARCHAR2(100)   NOT NULL,
    START_HOUR              NUMBER          NOT NULL,
    END_HOUR                NUMBER          NOT NULL,
    MAX_ORDERS              NUMBER          DEFAULT 50 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MH_DELIVERY_SLOT PRIMARY KEY (DELIVERY_SLOT_ID),
    CONSTRAINT UQ_MH_DELIVERY_SLOT_CODE UNIQUE (SLOT_CODE),
    CONSTRAINT CK_MH_DELIVERY_SLOT_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE MH_PICKUP_STORE (
    PICKUP_STORE_ID         NUMBER          NOT NULL,
    STORE_CODE              VARCHAR2(50)    NOT NULL,
    STORE_NAME              VARCHAR2(150)   NOT NULL,
    BRANCH_ID               NUMBER,
    ADDRESS_LINE            VARCHAR2(300),
    CITY                    VARCHAR2(100),
    OPEN_HOUR               NUMBER          DEFAULT 9 NOT NULL,
    CLOSE_HOUR              NUMBER          DEFAULT 21 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MH_PICKUP_STORE PRIMARY KEY (PICKUP_STORE_ID),
    CONSTRAINT UQ_MH_PICKUP_STORE_CODE UNIQUE (STORE_CODE),
    CONSTRAINT CK_MH_PICKUP_STORE_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);
