-- Stock reservations during checkout (prevent overselling).

CREATE TABLE MH_INVENTORY_RESERVATION (
    RESERVATION_ID          NUMBER          NOT NULL,
    CART_ID                 NUMBER,
    ORDER_ID                NUMBER,
    USER_ID                 NUMBER,
    LOCATION_CODE           NUMBER          NOT NULL,
    ITEM_CODE               NUMBER          NOT NULL,
    QUANTITY                NUMBER(12,3)    NOT NULL,
    RESERVATION_STATUS      VARCHAR2(30)    DEFAULT 'ACTIVE' NOT NULL,
    EXPIRES_AT              TIMESTAMP       NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    CONSTRAINT PK_MH_INVENTORY_RESERVATION PRIMARY KEY (RESERVATION_ID),
    CONSTRAINT CK_MH_RESERVATION_STATUS CHECK (
        RESERVATION_STATUS IN ('ACTIVE', 'RELEASED', 'CONVERTED', 'EXPIRED')
    ),
    CONSTRAINT CK_MH_RESERVATION_QTY CHECK (QUANTITY > 0)
);

CREATE INDEX IX_MH_RESERVATION_CART ON MH_INVENTORY_RESERVATION (CART_ID, RESERVATION_STATUS);
CREATE INDEX IX_MH_RESERVATION_ITEM ON MH_INVENTORY_RESERVATION (LOCATION_CODE, ITEM_CODE, RESERVATION_STATUS);
