-- =============================================================================
-- CATEGORY / BRAND / AGE_GROUP
-- =============================================================================

CREATE TABLE CATEGORY (
    CATEGORY_ID             NUMBER          NOT NULL,
    PARENT_CATEGORY_ID      NUMBER,
    CATEGORY_CODE           VARCHAR2(50)    NOT NULL,
    CATEGORY_NAME           VARCHAR2(200)   NOT NULL,
    SLUG                    VARCHAR2(220)   NOT NULL,
    DESCRIPTION             VARCHAR2(1000),
    IMAGE_URL               VARCHAR2(500),
    SORT_ORDER              NUMBER          DEFAULT 0 NOT NULL,
    LEVEL_NO                NUMBER          DEFAULT 1 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_CATEGORY PRIMARY KEY (CATEGORY_ID),
    CONSTRAINT UQ_CATEGORY_CODE UNIQUE (CATEGORY_CODE),
    CONSTRAINT UQ_CATEGORY_SLUG UNIQUE (SLUG),
    CONSTRAINT CK_CATEGORY_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_CATEGORY_LEVEL CHECK (LEVEL_NO >= 1)
);

CREATE TABLE BRAND (
    BRAND_ID                NUMBER          NOT NULL,
    BRAND_CODE              VARCHAR2(50)    NOT NULL,
    BRAND_NAME              VARCHAR2(200)   NOT NULL,
    SLUG                    VARCHAR2(220)   NOT NULL,
    DESCRIPTION             VARCHAR2(1000),
    LOGO_URL                VARCHAR2(500),
    WEBSITE_URL             VARCHAR2(500),
    SORT_ORDER              NUMBER          DEFAULT 0 NOT NULL,
    IS_FEATURED             NUMBER(1)       DEFAULT 0 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_BRAND PRIMARY KEY (BRAND_ID),
    CONSTRAINT UQ_BRAND_CODE UNIQUE (BRAND_CODE),
    CONSTRAINT UQ_BRAND_SLUG UNIQUE (SLUG),
    CONSTRAINT CK_BRAND_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_BRAND_FEATURED CHECK (IS_FEATURED IN (0, 1))
);

CREATE TABLE AGE_GROUP (
    AGE_GROUP_ID            NUMBER          NOT NULL,
    AGE_GROUP_CODE          VARCHAR2(50)    NOT NULL,
    AGE_GROUP_NAME          VARCHAR2(100)   NOT NULL,
    SLUG                    VARCHAR2(120)   NOT NULL,
    MIN_AGE_MONTHS          NUMBER          DEFAULT 0 NOT NULL,
    MAX_AGE_MONTHS          NUMBER,
    DESCRIPTION             VARCHAR2(500),
    SORT_ORDER              NUMBER          DEFAULT 0 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_AGE_GROUP PRIMARY KEY (AGE_GROUP_ID),
    CONSTRAINT UQ_AGE_GROUP_CODE UNIQUE (AGE_GROUP_CODE),
    CONSTRAINT UQ_AGE_GROUP_SLUG UNIQUE (SLUG),
    CONSTRAINT CK_AGE_GROUP_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_AGE_GROUP_RANGE CHECK (
        MAX_AGE_MONTHS IS NULL OR MAX_AGE_MONTHS >= MIN_AGE_MONTHS
    )
);
