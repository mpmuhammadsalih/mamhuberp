-- Loyalty program tables (MH_ prefix).

CREATE TABLE MH_LOYALTY_TIER (
    TIER_ID                 NUMBER          NOT NULL,
    TIER_CODE               VARCHAR2(30)    NOT NULL,
    TIER_NAME               VARCHAR2(100)   NOT NULL,
    MIN_LIFETIME_POINTS     NUMBER          DEFAULT 0 NOT NULL,
    BONUS_EARN_PERCENT      NUMBER(5,2)     DEFAULT 0 NOT NULL,
    SORT_ORDER              NUMBER          DEFAULT 0 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MH_LOYALTY_TIER PRIMARY KEY (TIER_ID),
    CONSTRAINT UQ_MH_LOYALTY_TIER_CODE UNIQUE (TIER_CODE),
    CONSTRAINT CK_MH_LOYALTY_TIER_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE MH_LOYALTY_RULE (
    RULE_ID                 NUMBER          NOT NULL,
    RULE_CODE               VARCHAR2(50)    NOT NULL,
    RULE_NAME               VARCHAR2(200)   NOT NULL,
    EARN_SPEND_AMOUNT       NUMBER(18,4)    DEFAULT 100 NOT NULL,
    EARN_POINTS             NUMBER          DEFAULT 1 NOT NULL,
    REDEEM_POINTS           NUMBER          DEFAULT 10 NOT NULL,
    REDEEM_VALUE            NUMBER(18,4)    DEFAULT 1 NOT NULL,
    MIN_REDEEM_POINTS       NUMBER          DEFAULT 10 NOT NULL,
    MAX_REDEEM_PERCENT      NUMBER(5,2)     DEFAULT 50 NOT NULL,
    POINTS_EXPIRY_DAYS      NUMBER,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    MODIFIED_AT             TIMESTAMP,
    CONSTRAINT PK_MH_LOYALTY_RULE PRIMARY KEY (RULE_ID),
    CONSTRAINT UQ_MH_LOYALTY_RULE_CODE UNIQUE (RULE_CODE),
    CONSTRAINT CK_MH_LOYALTY_RULE_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE MH_LOYALTY_ACCOUNT (
    ACCOUNT_ID              NUMBER          NOT NULL,
    USER_ID                 NUMBER          NOT NULL,
    MEMBERSHIP_NUMBER       VARCHAR2(30)    NOT NULL,
    TIER_ID                 NUMBER,
    POINTS_BALANCE          NUMBER          DEFAULT 0 NOT NULL,
    LIFETIME_POINTS         NUMBER          DEFAULT 0 NOT NULL,
    LIFETIME_SPEND          NUMBER(18,4)    DEFAULT 0 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    MODIFIED_AT             TIMESTAMP,
    CONSTRAINT PK_MH_LOYALTY_ACCOUNT PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT UQ_MH_LOYALTY_ACCOUNT_USER UNIQUE (USER_ID),
    CONSTRAINT UQ_MH_LOYALTY_MEMBERSHIP UNIQUE (MEMBERSHIP_NUMBER),
    CONSTRAINT CK_MH_LOYALTY_ACCOUNT_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE MH_LOYALTY_TRANSACTION (
    TRANSACTION_ID          NUMBER          NOT NULL,
    ACCOUNT_ID              NUMBER          NOT NULL,
    USER_ID                 NUMBER          NOT NULL,
    TRANSACTION_TYPE        VARCHAR2(20)    NOT NULL,
    POINTS                  NUMBER          NOT NULL,
    ORDER_ID                NUMBER,
    DESCRIPTION             VARCHAR2(500),
    BALANCE_AFTER           NUMBER          NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MH_LOYALTY_TRANSACTION PRIMARY KEY (TRANSACTION_ID),
    CONSTRAINT CK_MH_LOYALTY_TX_TYPE CHECK (
        TRANSACTION_TYPE IN ('EARN', 'REDEEM', 'EXPIRE', 'ADJUST', 'BONUS')
    )
);

CREATE INDEX IX_MH_LOYALTY_TX_USER ON MH_LOYALTY_TRANSACTION (USER_ID, CREATED_AT);
CREATE INDEX IX_MH_LOYALTY_TX_ORDER ON MH_LOYALTY_TRANSACTION (ORDER_ID);
