-- =============================================================================
-- COMPANY / BRANCH / WAREHOUSE
-- =============================================================================

CREATE TABLE COMPANY (
    COMPANY_ID              NUMBER          NOT NULL,
    COMPANY_CODE            VARCHAR2(30)    NOT NULL,
    COMPANY_NAME            VARCHAR2(200)   NOT NULL,
    LEGAL_NAME              VARCHAR2(200),
    TAX_NUMBER              VARCHAR2(50),
    EMAIL                   VARCHAR2(255),
    PHONE                   VARCHAR2(30),
    WEBSITE                 VARCHAR2(255),
    CURRENCY_CODE           VARCHAR2(3)     DEFAULT 'QAR' NOT NULL,
    COUNTRY_CODE            VARCHAR2(2)     DEFAULT 'QA' NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_COMPANY PRIMARY KEY (COMPANY_ID),
    CONSTRAINT UQ_COMPANY_CODE UNIQUE (COMPANY_CODE),
    CONSTRAINT CK_COMPANY_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE BRANCH (
    BRANCH_ID               NUMBER          NOT NULL,
    COMPANY_ID              NUMBER          NOT NULL,
    BRANCH_CODE             VARCHAR2(30)    NOT NULL,
    BRANCH_NAME             VARCHAR2(200)   NOT NULL,
    BRANCH_TYPE             VARCHAR2(30)    DEFAULT 'STORE' NOT NULL,
    EMAIL                   VARCHAR2(255),
    PHONE                   VARCHAR2(30),
    ADDRESS_LINE1           VARCHAR2(255),
    ADDRESS_LINE2           VARCHAR2(255),
    CITY                    VARCHAR2(100),
    COUNTRY_CODE            VARCHAR2(2)     DEFAULT 'QA' NOT NULL,
    LATITUDE                NUMBER(10,7),
    LONGITUDE               NUMBER(10,7),
    IS_ONLINE_FULFILLMENT   NUMBER(1)       DEFAULT 1 NOT NULL,
    IS_PICKUP_ENABLED       NUMBER(1)       DEFAULT 1 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_BRANCH PRIMARY KEY (BRANCH_ID),
    CONSTRAINT UQ_BRANCH_CODE UNIQUE (BRANCH_CODE),
    CONSTRAINT CK_BRANCH_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_BRANCH_ONLINE CHECK (IS_ONLINE_FULFILLMENT IN (0, 1)),
    CONSTRAINT CK_BRANCH_PICKUP CHECK (IS_PICKUP_ENABLED IN (0, 1)),
    CONSTRAINT CK_BRANCH_TYPE CHECK (
        BRANCH_TYPE IN ('STORE', 'WAREHOUSE', 'ONLINE', 'HQ')
    )
);

CREATE TABLE WAREHOUSE (
    WAREHOUSE_ID            NUMBER          NOT NULL,
    BRANCH_ID               NUMBER          NOT NULL,
    WAREHOUSE_CODE          VARCHAR2(30)    NOT NULL,
    WAREHOUSE_NAME          VARCHAR2(200)   NOT NULL,
    WAREHOUSE_TYPE          VARCHAR2(30)    DEFAULT 'MAIN' NOT NULL,
    IS_DEFAULT              NUMBER(1)       DEFAULT 0 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_WAREHOUSE PRIMARY KEY (WAREHOUSE_ID),
    CONSTRAINT UQ_WAREHOUSE_CODE UNIQUE (WAREHOUSE_CODE),
    CONSTRAINT CK_WAREHOUSE_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_WAREHOUSE_DEFAULT CHECK (IS_DEFAULT IN (0, 1)),
    CONSTRAINT CK_WAREHOUSE_TYPE CHECK (
        WAREHOUSE_TYPE IN ('MAIN', 'STORE', 'RETURNS', 'TRANSIT')
    )
);
