-- Reviews, CMS pages, and in-app notifications (MH_ prefix).

CREATE TABLE MH_REVIEW (
    REVIEW_ID               NUMBER          NOT NULL,
    USER_ID                 NUMBER          NOT NULL,
    LOCATION_CODE           NUMBER          NOT NULL,
    ITEM_CODE               NUMBER          NOT NULL,
    ORDER_ID                NUMBER,
    RATING                  NUMBER(1)       NOT NULL,
    TITLE                   VARCHAR2(200),
    REVIEW_TEXT             VARCHAR2(4000),
    IS_VERIFIED_PURCHASE    NUMBER(1)       DEFAULT 0 NOT NULL,
    STATUS                  VARCHAR2(20)    DEFAULT 'PENDING' NOT NULL,
    HELPFUL_COUNT           NUMBER          DEFAULT 0 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    MODIFIED_AT             TIMESTAMP,
    CONSTRAINT PK_MH_REVIEW PRIMARY KEY (REVIEW_ID),
    CONSTRAINT CK_MH_REVIEW_RATING CHECK (RATING BETWEEN 1 AND 5),
    CONSTRAINT CK_MH_REVIEW_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'HIDDEN')),
    CONSTRAINT CK_MH_REVIEW_VERIFIED CHECK (IS_VERIFIED_PURCHASE IN (0, 1))
);

CREATE TABLE MH_CMS_PAGE (
    CMS_PAGE_ID             NUMBER          NOT NULL,
    PAGE_CODE               VARCHAR2(80)    NOT NULL,
    PAGE_TITLE              VARCHAR2(200)   NOT NULL,
    SLUG                    VARCHAR2(120)   NOT NULL,
    PAGE_TYPE               VARCHAR2(40)    DEFAULT 'STATIC' NOT NULL,
    CONTENT_HTML            CLOB,
    META_DESCRIPTION        VARCHAR2(500),
    IS_PUBLISHED            NUMBER(1)       DEFAULT 1 NOT NULL,
    SORT_ORDER              NUMBER          DEFAULT 0 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    MODIFIED_AT             TIMESTAMP,
    CONSTRAINT PK_MH_CMS_PAGE PRIMARY KEY (CMS_PAGE_ID),
    CONSTRAINT UQ_MH_CMS_PAGE_CODE UNIQUE (PAGE_CODE),
    CONSTRAINT UQ_MH_CMS_PAGE_SLUG UNIQUE (SLUG),
    CONSTRAINT CK_MH_CMS_PUBLISHED CHECK (IS_PUBLISHED IN (0, 1))
);

CREATE TABLE MH_NOTIFICATION (
    NOTIFICATION_ID         NUMBER          NOT NULL,
    USER_ID                 NUMBER          NOT NULL,
    CHANNEL                 VARCHAR2(20)    DEFAULT 'IN_APP' NOT NULL,
    NOTIFICATION_TYPE       VARCHAR2(60)    NOT NULL,
    TITLE                   VARCHAR2(200)   NOT NULL,
    BODY                    VARCHAR2(2000),
    REF_ENTITY              VARCHAR2(60),
    REF_ENTITY_ID           NUMBER,
    IS_READ                 NUMBER(1)       DEFAULT 0 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    READ_AT                 TIMESTAMP,
    CONSTRAINT PK_MH_NOTIFICATION PRIMARY KEY (NOTIFICATION_ID),
    CONSTRAINT CK_MH_NOTIF_READ CHECK (IS_READ IN (0, 1))
);

CREATE INDEX IX_MH_REVIEW_ITEM ON MH_REVIEW (LOCATION_CODE, ITEM_CODE, STATUS);
CREATE INDEX IX_MH_NOTIF_USER ON MH_NOTIFICATION (USER_ID, IS_READ, CREATED_AT);
