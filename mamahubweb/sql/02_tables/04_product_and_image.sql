-- =============================================================================
-- PRODUCT / PRODUCT_IMAGE
-- =============================================================================

CREATE TABLE PRODUCT (
    PRODUCT_ID              NUMBER          NOT NULL,
    SKU                     VARCHAR2(50)    NOT NULL,
    INTERNAL_ITEM_CODE      VARCHAR2(50),
    BARCODE                 VARCHAR2(50),
    PRODUCT_NAME            VARCHAR2(300)   NOT NULL,
    SLUG                    VARCHAR2(320)   NOT NULL,
    SHORT_DESCRIPTION       VARCHAR2(1000),
    FULL_DESCRIPTION        CLOB,
    BRAND_ID                NUMBER,
    CATEGORY_ID             NUMBER,
    MIN_AGE_MONTHS          NUMBER,
    MAX_AGE_MONTHS          NUMBER,
    IS_GENDER_NEUTRAL       NUMBER(1)       DEFAULT 1 NOT NULL,
    PRODUCT_TYPE            VARCHAR2(50)    DEFAULT 'SIMPLE' NOT NULL,
    TAX_CATEGORY            VARCHAR2(50),
    COST_PRICE              NUMBER(14,3),
    REGULAR_PRICE           NUMBER(14,3)    NOT NULL,
    OFFER_PRICE             NUMBER(14,3),
    CURRENCY_CODE           VARCHAR2(3)     DEFAULT 'QAR' NOT NULL,
    STOCK_STATUS            VARCHAR2(30)    DEFAULT 'IN_STOCK' NOT NULL,
    WEIGHT_KG               NUMBER(10,3),
    LENGTH_CM               NUMBER(10,2),
    WIDTH_CM                NUMBER(10,2),
    HEIGHT_CM               NUMBER(10,2),
    COUNTRY_OF_ORIGIN       VARCHAR2(100),
    MANUFACTURER            VARCHAR2(200),
    WARRANTY_DETAILS        VARCHAR2(500),
    SAFETY_WARNING          VARCHAR2(1000),
    MATERIAL                VARCHAR2(200),
    COLOR_NAME              VARCHAR2(100),
    BATTERY_REQUIRED        NUMBER(1)       DEFAULT 0 NOT NULL,
    BATTERY_INCLUDED        NUMBER(1)       DEFAULT 0 NOT NULL,
    ASSEMBLY_REQUIRED       NUMBER(1)       DEFAULT 0 NOT NULL,
    MAX_SUPPORTED_WEIGHT_KG NUMBER(10,2),
    IS_RETURN_ELIGIBLE      NUMBER(1)       DEFAULT 1 NOT NULL,
    IS_FEATURED             NUMBER(1)       DEFAULT 0 NOT NULL,
    IS_NEW_ARRIVAL          NUMBER(1)       DEFAULT 0 NOT NULL,
    IS_BEST_SELLER          NUMBER(1)       DEFAULT 0 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_PRODUCT PRIMARY KEY (PRODUCT_ID),
    CONSTRAINT UQ_PRODUCT_SKU UNIQUE (SKU),
    CONSTRAINT UQ_PRODUCT_SLUG UNIQUE (SLUG),
    CONSTRAINT UQ_PRODUCT_BARCODE UNIQUE (BARCODE),
    CONSTRAINT CK_PRODUCT_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_PRODUCT_GENDER CHECK (IS_GENDER_NEUTRAL IN (0, 1)),
    CONSTRAINT CK_PRODUCT_BATTERY_REQ CHECK (BATTERY_REQUIRED IN (0, 1)),
    CONSTRAINT CK_PRODUCT_BATTERY_INC CHECK (BATTERY_INCLUDED IN (0, 1)),
    CONSTRAINT CK_PRODUCT_ASSEMBLY CHECK (ASSEMBLY_REQUIRED IN (0, 1)),
    CONSTRAINT CK_PRODUCT_RETURN CHECK (IS_RETURN_ELIGIBLE IN (0, 1)),
    CONSTRAINT CK_PRODUCT_FEATURED CHECK (IS_FEATURED IN (0, 1)),
    CONSTRAINT CK_PRODUCT_NEW CHECK (IS_NEW_ARRIVAL IN (0, 1)),
    CONSTRAINT CK_PRODUCT_BEST CHECK (IS_BEST_SELLER IN (0, 1)),
    CONSTRAINT CK_PRODUCT_PRICE CHECK (REGULAR_PRICE >= 0),
    CONSTRAINT CK_PRODUCT_OFFER CHECK (
        OFFER_PRICE IS NULL OR (OFFER_PRICE >= 0 AND OFFER_PRICE <= REGULAR_PRICE)
    ),
    CONSTRAINT CK_PRODUCT_STOCK CHECK (
        STOCK_STATUS IN ('IN_STOCK', 'OUT_OF_STOCK', 'PREORDER', 'DISCONTINUED')
    ),
    CONSTRAINT CK_PRODUCT_TYPE CHECK (
        PRODUCT_TYPE IN ('SIMPLE', 'VARIABLE', 'BUNDLE', 'DIGITAL')
    ),
    CONSTRAINT CK_PRODUCT_AGE CHECK (
        MAX_AGE_MONTHS IS NULL
        OR MIN_AGE_MONTHS IS NULL
        OR MAX_AGE_MONTHS >= MIN_AGE_MONTHS
    )
);

CREATE TABLE PRODUCT_IMAGE (
    PRODUCT_IMAGE_ID        NUMBER          NOT NULL,
    PRODUCT_ID              NUMBER          NOT NULL,
    IMAGE_URL               VARCHAR2(500)   NOT NULL,
    ALT_TEXT                VARCHAR2(255),
    SORT_ORDER              NUMBER          DEFAULT 0 NOT NULL,
    IS_PRIMARY              NUMBER(1)       DEFAULT 0 NOT NULL,
    IS_ACTIVE               NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY              NUMBER,
    MODIFIED_AT             TIMESTAMP,
    MODIFIED_BY             NUMBER,
    CONSTRAINT PK_PRODUCT_IMAGE PRIMARY KEY (PRODUCT_IMAGE_ID),
    CONSTRAINT CK_PRODUCT_IMAGE_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_PRODUCT_IMAGE_PRIMARY CHECK (IS_PRIMARY IN (0, 1))
);
