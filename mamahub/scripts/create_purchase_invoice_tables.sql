-- =============================================================================
-- Purchase Invoice tables (Oracle)
-- Run this in your Oracle DB to create tables for Purchase Invoice module.
-- Flow: Purchase Order (LPOHDR/LPODTL) -> Goods Receipt (ReceiptHdr/ReceiptDtl)
--       -> Purchase Invoice (PURCHASEINVOICEHDR / PURCHASEINVOICEDTL)
-- =============================================================================

-- Header: one row per supplier purchase invoice
CREATE TABLE PURCHASEINVOICEHDR (
  LOCATIONCODE     NUMBER NOT NULL,
  RESETNO          NUMBER DEFAULT 1 NOT NULL,
  PURCHASEINVOICENO NUMBER NOT NULL,
  INVOICEDATE      DATE NOT NULL,
  SUPPLIERCODE     NUMBER NOT NULL,
  SUPPLIERINVOICENO VARCHAR2(50),
  SUPPLIERINVOICEDATE DATE,
  RECEIPTNO        NUMBER,
  RECEIPTRESETNO   NUMBER,
  LPONO            NUMBER,
  LPORESETNO       NUMBER,
  SUBTOTAL         NUMBER(18,3) DEFAULT 0,
  DISCOUNT         NUMBER(18,3) DEFAULT 0,
  VATAMOUNT        NUMBER(18,3) DEFAULT 0,
  TOTALAMOUNT      NUMBER(18,3) DEFAULT 0,
  CURRENCYCODE     VARCHAR2(10),
  EXCHANGERATE     NUMBER(18,6) DEFAULT 1,
  REMARKS          VARCHAR2(500),
  DELFLAG          VARCHAR2(1) DEFAULT 'N',
  CREATEDBY        VARCHAR2(50),
  CREATEDDATE      DATE,
  MODIFIEDBY       VARCHAR2(50),
  MODIFIEDDATE     DATE,
  DUEDATE          DATE,
  CONSTRAINT PK_PURCHASEINVOICEHDR PRIMARY KEY (LOCATIONCODE, RESETNO, PURCHASEINVOICENO)
);

CREATE INDEX IX_PIH_SUPPLIER ON PURCHASEINVOICEHDR(SUPPLIERCODE);
CREATE INDEX IX_PIH_RECEIPT ON PURCHASEINVOICEHDR(RECEIPTNO, RECEIPTRESETNO);
CREATE INDEX IX_PIH_LPO ON PURCHASEINVOICEHDR(LPONO, LPORESETNO);
CREATE INDEX IX_PIH_DATE ON PURCHASEINVOICEHDR(INVOICEDATE);

-- Detail: one row per line on the purchase invoice (linked to GRN/Receipt if needed)
CREATE TABLE PURCHASEINVOICEDTL (
  LOCATIONCODE       NUMBER NOT NULL,
  RESETNO            NUMBER NOT NULL,
  PURCHASEINVOICENO  NUMBER NOT NULL,
  LINENO             NUMBER NOT NULL,
  ITEMCODE           NUMBER NOT NULL,
  UNITOFMEASUREMENT  VARCHAR2(20),
  QUANTITY           NUMBER(18,3) DEFAULT 0,
  RATE               NUMBER(18,3) DEFAULT 0,
  AMOUNT             NUMBER(18,3) DEFAULT 0,
  BONUS              NUMBER(18,3) DEFAULT 0,
  DISCOUNT           NUMBER(18,3) DEFAULT 0,
  OTHERCHARGE        NUMBER(18,3) DEFAULT 0,
  VATPERCENT         NUMBER(8,2) DEFAULT 0,
  VATAMOUNT          NUMBER(18,3) DEFAULT 0,
  TOTALAMOUNT        NUMBER(18,3) DEFAULT 0,
  RECEIPTNO          NUMBER,
  RECEIPTRESETNO     NUMBER,
  STORE              VARCHAR2(50),
  BASEQTY            NUMBER(18,3),
  LANDINGCOST        NUMBER(18,3),
  CONSTRAINT PK_PURCHASEINVOICEDTL PRIMARY KEY (LOCATIONCODE, RESETNO, PURCHASEINVOICENO, LINENO),
  CONSTRAINT FK_PID_PIH FOREIGN KEY (LOCATIONCODE, RESETNO, PURCHASEINVOICENO)
    REFERENCES PURCHASEINVOICEHDR(LOCATIONCODE, RESETNO, PURCHASEINVOICENO)
);

CREATE INDEX IX_PID_ITEM ON PURCHASEINVOICEDTL(ITEMCODE);
CREATE INDEX IX_PID_RECEIPT ON PURCHASEINVOICEDTL(RECEIPTNO, RECEIPTRESETNO);

-- Optional: sequence for next Purchase Invoice number per location/reset (if you use sequence)
-- CREATE SEQUENCE SEQ_PURCHASEINVOICENO START WITH 1 INCREMENT BY 1 NOCACHE;

COMMENT ON TABLE PURCHASEINVOICEHDR IS 'Purchase Invoice header - one per supplier invoice';
COMMENT ON TABLE PURCHASEINVOICEDTL IS 'Purchase Invoice detail lines - items and amounts';
