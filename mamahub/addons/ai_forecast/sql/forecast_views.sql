-- Optional Oracle views for AI Forecasting (adjust table names to your schema).
-- Run manually on tenant DB if you prefer SQL views over Python aggregation.

-- Daily sales (excludes cancelled/deleted headers when columns exist)
CREATE OR REPLACE VIEW V_AI_DAILY_SALES AS
SELECT TRUNC(h.BILLDATE) AS sale_date,
       h.LOCATIONCODE,
       SUM(ABS(NVL(d.QUANTITY,0))) AS qty,
       SUM(ABS(NVL(d.QUANTITY,0)) * (NVL(d.RATE,0) - NVL(d.ITDISC,0))) AS amount
FROM BILLHDRHISTORY h
INNER JOIN BILLDTLHISTORY d ON d.BILLNO = h.BILLNO AND d.LOCATIONCODE = h.LOCATIONCODE
WHERE NVL(h.CANCELFLAG,'N') <> 'Y'
GROUP BY TRUNC(h.BILLDATE), h.LOCATIONCODE;

-- Item velocity (90-day window example)
CREATE OR REPLACE VIEW V_AI_ITEM_VELOCITY AS
SELECT d.ITEMCODE,
       h.LOCATIONCODE,
       SUM(CASE WHEN NVL(d.QUANTITY,0) > 0 THEN d.QUANTITY ELSE 0 END) AS sold_qty,
       SUM(CASE WHEN NVL(d.QUANTITY,0) < 0 THEN ABS(d.QUANTITY) ELSE 0 END) AS return_qty
FROM BILLHDRHISTORY h
INNER JOIN BILLDTLHISTORY d ON d.BILLNO = h.BILLNO
WHERE h.BILLDATE >= TRUNC(SYSDATE) - 90
GROUP BY d.ITEMCODE, h.LOCATIONCODE;

-- Supplier lead time (LPO to GRN)
CREATE OR REPLACE VIEW V_AI_SUPPLIER_LEAD AS
SELECT h.SUPPLIERCODE,
       AVG(r.RECEIPTDATE - l.LPODATE) AS avg_lead_days,
       COUNT(*) AS sample_size
FROM RECEIPTHDR r
INNER JOIN LPOHDR l ON l.LPONO = r.LPONO AND l.LOCATIONCODE = r.LOCATIONCODE
INNER JOIN LPOHDR h ON h.LPONO = l.LPONO
WHERE r.LPONO > 0 AND r.RECEIPTDATE >= TRUNC(SYSDATE) - 365
GROUP BY h.SUPPLIERCODE;

-- Pending LPO qty (no receipt yet)
CREATE OR REPLACE VIEW V_AI_PENDING_LPO AS
SELECT d.ITEMCODE, d.LOCATIONCODE, SUM(NVL(d.QUANTITY,0)) AS pending_qty
FROM LPODTL d
INNER JOIN LPOHDR h ON h.LPONO = d.LPONO AND h.LOCATIONCODE = d.LOCATIONCODE
WHERE NOT EXISTS (
  SELECT 1 FROM RECEIPTHDR r
  WHERE r.LPONO = h.LPONO AND r.LOCATIONCODE = h.LOCATIONCODE
)
GROUP BY d.ITEMCODE, d.LOCATIONCODE;
