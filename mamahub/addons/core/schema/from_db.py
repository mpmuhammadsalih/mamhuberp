"""
Load introspected Oracle models from ``addons/core/schema/generated/*.py``.

Generated by ``scripts/oracle_introspect_models.py``.

Set ``ORACLE_SCHEMA_MODULE`` to the generated module basename (no ``.py``),
e.g. ``oracle_schema_rfim``. Otherwise the first existing module among
``db_schema``, ``oracle_schema_rfim``, ``oracle_schema`` is used.
"""
from __future__ import annotations
import importlib
import os
from types import ModuleType
_fallback_order = ('db_schema', 'oracle_schema_rfim', 'oracle_schema')
_cached_module: ModuleType | None = None

def preferred_short_name() -> str:
    e = os.getenv('ORACLE_SCHEMA_MODULE', '').strip()
    if not e:
        return ''
    e = e[:-3] if e.lower().endswith('.py') else e
    e = e.replace('\\', '/')
    if '/' in e:
        e = e.rsplit('/', 1)[-1]
    if '.' in e:
        e = e.rsplit('.', 1)[-1]
    return e

def _module_search_order() -> list[str]:
    p = preferred_short_name()
    out: list[str] = []
    if p:
        out.append(p)
    for name in _fallback_order:
        if name not in out:
            out.append(name)
    return out

def load_generated_schema() -> ModuleType:
    """Import the generated schema package (first that succeeds with ``TABLE_BUNDLE``)."""
    global _cached_module
    if _cached_module is not None:
        return _cached_module
    errs: list[str] = []
    for short in _module_search_order():
        fq = f'addons.core.schema.generated.{short}'
        try:
            mod = importlib.import_module(fq)
            if getattr(mod, 'TABLE_BUNDLE', None) is not None:
                _cached_module = mod
                return mod
            errs.append(f'{fq}: no TABLE_BUNDLE')
        except ImportError as ex:
            errs.append(f'{fq}: {ex}')
    raise ImportError('No generated Oracle schema.\nRun: python scripts/oracle_introspect_models.py --profile rfim\nor set ORACLE_SCHEMA_MODULE to the basename under addons/core/schema/generated/\n' + '; '.join(errs)) from None

def get_table_bundle():
    """Snake-case attribute names pointing at Oracle logical table strings."""
    return load_generated_schema().TABLE_BUNDLE

def get_cols_by_table() -> dict:
    """``UPPER_ORACLE_TABLE`` → generated ``*Cols`` class."""
    m = getattr(load_generated_schema(), 'COLS_BY_TABLE', None)
    return dict(m) if m else {}

def has_generated_schema() -> bool:
    """True when usable generated schema exists (``addons/core/schema/generated/*.py``)."""
    for short in _module_search_order():
        fq = f'addons.core.schema.generated.{short}'
        try:
            mod = importlib.import_module(fq)
            if getattr(mod, 'TABLE_BUNDLE', None) is not None:
                return True
        except ImportError:
            continue
    return False

def cols_for_table(name: str):
    """Resolved ``*Cols`` class for Oracle table ``name``, or ``None``."""
    mod = load_generated_schema()
    fn = getattr(mod, 'cols_for_table', None)
    if callable(fn):
        return fn(name)
    m = getattr(mod, 'COLS_BY_TABLE', None)
    if isinstance(m, dict):
        return m.get((name or '').strip().upper())
    return None

def primary_key_columns(name: str):
    """Ordered PK column names for ``name`` if the generated module includes constraint metadata; else ``None``."""
    mod = load_generated_schema()
    fn = getattr(mod, 'primary_key_columns', None)
    return fn(name) if callable(fn) else None

def foreign_keys_from_table(name: str):
    """FK rows where ``name`` is the child (referencing) table; empty tuple if unsupported."""
    mod = load_generated_schema()
    fn = getattr(mod, 'foreign_keys_from_table', None)
    return fn(name) if callable(fn) else ()

def foreign_keys_to_table(name: str):
    """FK rows that reference ``name`` as parent; empty tuple if unsupported."""
    mod = load_generated_schema()
    fn = getattr(mod, 'foreign_keys_to_table', None)
    return fn(name) if callable(fn) else ()

def indexes_on_table(name: str):
    """Index definitions on ``name``; empty tuple if unsupported."""
    mod = load_generated_schema()
    fn = getattr(mod, 'indexes_on_table', None)
    return fn(name) if callable(fn) else ()
__all__ = ['cols_for_table', 'foreign_keys_from_table', 'foreign_keys_to_table', 'get_cols_by_table', 'get_table_bundle', 'has_generated_schema', 'indexes_on_table', 'load_generated_schema', 'primary_key_columns']
